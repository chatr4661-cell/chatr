/**
 * Registry Helper Functions
 */
export function getDomainProperty(hostname: string): DomainProperty | undefined {
  const cleanHost = hostname.toLowerCase().trim().replace(/^https?:\/\//, '').replace(/\/.*$/, '');
  return ECOSYSTEM_REGISTRY.find(d => d.hostname === cleanHost);
}

export function getPropertiesByEntity(entityId: BusinessEntityId): DomainProperty[] {
  return ECOSYSTEM_REGISTRY.filter(d => d.entityId === entityId);
}

export function getAllCanonicalOrigins(): string[] {
  return Array.from(new Set(ECOSYSTEM_REGISTRY.map(d => d.canonicalOrigin)));
}
